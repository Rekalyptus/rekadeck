"""Regenerate firmware/src/ca_roots.h: the root certificates the Rekadeck trusts for HTTPS.

    python3 tools/make_ca_roots.py path/to/cacert.pem      # Mozilla's list, e.g. from the certifi package

Only a short list, not all ~150 roots: every root the device trusts is parsed into RAM for each TLS connection, and
RAM is the tight resource on the board. The list covers the CAs behind most public HTTPS sites, including all of
Cloudflare's (Google Trust Services, Let's Encrypt, SSL.com) and Let's Encrypt for self-hosted servers. To trust
another CA, add its label from cacert.pem to ROOTS and run this again.
"""

import os
import re
import sys

ROOTS = [
    "ISRG Root X1",                           # Let's Encrypt
    "ISRG Root X2",
    "GTS Root R1",                            # Google Trust Services (rekalyptus.com via Cloudflare: GTS Root R4)
    "GTS Root R4",
    "SSL.com TLS RSA Root CA 2022",           # Cloudflare's other CA
    "SSL.com TLS ECC Root CA 2022",
    "DigiCert Global Root G2",
    "DigiCert Global Root CA",
    "Amazon Root CA 1",
    "USERTrust RSA Certification Authority",  # Sectigo
    "GlobalSign Root CA - R3",
]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "src", "ca_roots.h")


def main(bundle_path: str) -> None:
    text = open(bundle_path, encoding="utf-8").read()
    found = {}
    for m in re.finditer(r'# Label: "([^"]+)"\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----)',
                         text, re.S):
        found[m.group(1)] = m.group(2)
    missing = [r for r in ROOTS if r not in found]
    if missing:
        sys.exit("not in this bundle: " + ", ".join(missing))
    parts = []
    for name in ROOTS:
        parts.append(f"// {name}\n" + "\n".join(f'"{line}\\n"' for line in found[name].splitlines()))
    body = "\n".join(parts)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/make_ca_roots.py from Mozilla's CA list. The roots the Rekadeck trusts for HTTPS.\n")
        f.write("#pragma once\n\n")
        f.write("static const char CA_ROOTS_PEM[] =\n" + body + ";\n")
    print(f"wrote {len(ROOTS)} roots to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
