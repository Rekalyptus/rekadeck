"""Bakes Inter into 1-bit bitmap fonts for the device's own screens (setup, link code, sleep, menu).
Card text never needs these, the server draws cards. Run from the repo root:

    python3 tools/make_fonts.py

Writes firmware/lib/rekacore/src/fonts_data.cpp.
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "server", "rekaserver", "fonts")
OUT = os.path.join(ROOT, "firmware", "lib", "rekacore", "src", "fonts_data.cpp")
ASCII = "".join(chr(c) for c in range(32, 127))

FONTS = [  # name, file, px, characters
    ("FONT_SMALL", "Inter-Regular.ttf", 16, ASCII),
    ("FONT_SMALL_B", "Inter-SemiBold.ttf", 16, ASCII),
    ("FONT_BODY", "Inter-Regular.ttf", 22, ASCII),
    ("FONT_BODY_B", "Inter-SemiBold.ttf", 22, ASCII),
    ("FONT_TITLE", "Inter-SemiBold.ttf", 34, ASCII),
    ("FONT_CODE", "Inter-SemiBold.ttf", 64, ASCII),
    ("FONT_BIG", "Inter-SemiBold.ttf", 120, " 0123456789+"),
]


def bake(name, file, px, chars):
    f = ImageFont.truetype(os.path.join(TTF, file), px)
    ascent, descent = f.getmetrics()
    bitmap, glyphs = bytearray(), []
    for code in range(32, 127):
        ch = chr(code)
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w == 0 or h == 0:
            glyphs.append((len(bitmap), 0, 0, 0, 0, adv))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255)
        stride = (w + 7) // 8
        off = len(bitmap)
        px_ = img.load()
        for y in range(h):
            row = bytearray(stride)
            for x in range(w):
                if px_[x, y] >= 128:
                    row[x >> 3] |= 0x80 >> (x & 7)
            bitmap += row
        glyphs.append((off, w, h, x0, y0, adv))
    lines = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(bitmap), 24):
        lines.append("  " + ",".join(str(b) for b in bitmap[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const Glyph {name}_glyphs[] = {{")
    for g in glyphs:
        lines.append("  {%d,%d,%d,%d,%d,%d}," % g)
    lines.append("};")
    lines.append(f"const Font {name} = {{{name}_bits, {name}_glyphs, {ascent + descent}, {ascent}}};")
    return "\n".join(lines), len(bitmap)


def main():
    parts, total = [], 0
    for spec in FONTS:
        src, n = bake(*spec)
        parts.append(src)
        total += n
    with open(OUT, "w") as fh:
        fh.write("// Generated by tools/make_fonts.py from Inter (SIL Open Font License). Do not edit.\n")
        fh.write('#include "fonts.h"\n\nnamespace reka {\n\n' + "\n\n".join(parts) + "\n\n}  // namespace reka\n")
    print(f"wrote {OUT}: {total / 1024:.1f} KB of glyphs")


if __name__ == "__main__":
    main()
